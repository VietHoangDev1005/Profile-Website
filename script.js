const store = {
  get(key) { try { return localStorage.getItem(key); } catch { return null; } },
  set(key, value) { try { localStorage.setItem(key, value); } catch { /* storage unavailable */ } },
};

const i18nNodes = document.querySelectorAll("[data-i18n]");
const EN = {};
i18nNodes.forEach((el) => { EN[el.dataset.i18n] = el.innerHTML; });
EN["contact.copied"] = "Copied!";

let lang = store.get("lang") || (navigator.language.startsWith("vi") ? "vi" : "en");

function t(key) {
  return (lang === "vi" ? VI : EN)[key] ?? EN[key];
}

function applyLang() {
  document.documentElement.lang = lang;
  i18nNodes.forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  document.querySelectorAll("#langToggle [data-lang]").forEach((s) => s.classList.toggle("on", s.dataset.lang === lang));
  restartTyping();
}

document.getElementById("langToggle").addEventListener("click", () => {
  lang = lang === "en" ? "vi" : "en";
  store.set("lang", lang);
  applyLang();
});

// Theme
const root = document.documentElement;
root.dataset.theme = store.get("theme") || (matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark");
document.getElementById("themeToggle").addEventListener("click", () => {
  root.dataset.theme = root.dataset.theme === "dark" ? "light" : "dark";
  store.set("theme", root.dataset.theme);
});

// Typing effect for the role line
const typedEl = document.getElementById("typed");
const reduceMotion = matchMedia("(prefers-reduced-motion: reduce)").matches;
let typingTimer;

function restartTyping() {
  clearTimeout(typingTimer);
  const roles = ROLES[lang];
  if (reduceMotion) { typedEl.textContent = roles[0]; return; }
  let r = 0, i = 0, deleting = false;
  const tick = () => {
    const word = roles[r];
    i += deleting ? -1 : 1;
    typedEl.textContent = word.slice(0, i);
    let delay = deleting ? 35 : 70;
    if (!deleting && i === word.length) { deleting = true; delay = 1800; }
    else if (deleting && i === 0) { deleting = false; r = (r + 1) % roles.length; delay = 300; }
    typingTimer = setTimeout(tick, delay);
  };
  tick();
}

