// Highlight the nav link of the section in view, and reveal sections on scroll
const sections = document.querySelectorAll("main section[id]");
const revealTargets = document.querySelectorAll(".section, .stats");
revealTargets.forEach((el) => el.classList.add("reveal"));

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    entry.target.classList.add("in");
    if (entry.target.id) {
      navLinks.querySelectorAll("a").forEach((a) => a.classList.toggle("active", a.getAttribute("href") === `#${entry.target.id}`));
    }
  });
}, { rootMargin: "-30% 0px -60% 0px" });
sections.forEach((s) => observer.observe(s));

const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("in");
      revealObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.08 });
revealTargets.forEach((el) => revealObserver.observe(el));

