const store = {
  get(key) { try { return localStorage.getItem(key); } catch { return null; } },
  set(key, value) { try { localStorage.setItem(key, value); } catch { /* storage unavailable */ } },
};

// Language
const i18nNodes = document.querySelectorAll("[data-i18n]");
const EN = {};
i18nNodes.forEach((el) => { EN[el.dataset.i18n] = el.innerHTML; });

let lang = store.get("lang") || (navigator.language.startsWith("vi") ? "vi" : "en");

function applyLang() {
  const dict = lang === "vi" ? VI : EN;
  document.documentElement.lang = lang;
  i18nNodes.forEach((el) => { el.innerHTML = dict[el.dataset.i18n] ?? EN[el.dataset.i18n]; });
  document.querySelectorAll("#langToggle [data-lang]").forEach((s) => s.classList.toggle("on", s.dataset.lang === lang));
}

document.getElementById("langToggle").addEventListener("click", () => {
  lang = lang === "en" ? "vi" : "en";
  store.set("lang", lang);
  applyLang();
});

// Theme (initial value is set by the inline script in <head>)
const root = document.documentElement;
document.getElementById("themeToggle").addEventListener("click", () => {
  root.dataset.theme = root.dataset.theme === "dark" ? "light" : "dark";
  store.set("theme", root.dataset.theme);
});

// Highlight the sidebar link of the section in view
const tocLinks = document.querySelectorAll("#toc a");
const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    tocLinks.forEach((a) => a.classList.toggle("active", a.getAttribute("href") === `#${entry.target.id}`));
  });
}, { rootMargin: "-20% 0px -70% 0px" });
document.querySelectorAll("main section[id]").forEach((s) => observer.observe(s));

document.getElementById("year").textContent = new Date().getFullYear();
applyLang();
